const VOWELS_INDEP = { a: 'ಅ', e: 'ಎ', i: 'ಇ', o: 'ಒ', u: 'ಉ' };
const VOWELS_MATRA = { a: '', e: 'ೆ', i: 'ಿ', o: 'ೊ', u: 'ು' };
const DIGITS = { '0': '೦', '1': '೧', '2': '೨', '3': '೩', '4': '೪', '5': '೫', '6': '೬', '7': '೭', '8': '೮', '9': '೯' };

function transliterateWord(word) {
  const clean = word.toLowerCase().replace(/[^a-z0-9]/g, '');
  if (!clean) return '';
  if (WORD_REPLACEMENTS[clean]) return WORD_REPLACEMENTS[clean];
  if (/^\d+(st|nd|rd|th)?$/.test(clean)) {
    const num = clean.replace(/(st|nd|rd|th)$/, '');
    const knNum = num.split('').map(d => DIGITS[d] || d).join('');
    return clean.length > num.length ? `${knNum}ನೇ` : knNum;
  }

  let out = '';
  let i = 0;
  let prevWasConsonant = false;
  while (i < clean.length) {
    const ch = clean[i];
    if (DIGITS[ch]) {
      out += DIGITS[ch];
      prevWasConsonant = false;
      i++;
      continue;
    }
    const two = clean.slice(i, i + 2);
    const dig = DIGRAPHS.find(([k]) => k === two);
    if (dig) {
      if (two === 'ee' || two === 'oo' || two === 'ai' || two === 'au' || two === 'ou') {
        const matraMap = { ee: 'ೀ', oo: 'ೂ', ai: 'ೈ', au: 'ೌ', ou: 'ೌ' };
        out += prevWasConsonant ? matraMap[two] : dig[1];
        prevWasConsonant = false;
      } else {
        if (prevWasConsonant) out += '್';
        out += dig[1];
        prevWasConsonant = !dig[1].endsWith('್');
      }
      i += 2;
      continue;
    }
    if (VOWELS_INDEP[ch]) {
      out += prevWasConsonant ? VOWELS_MATRA[ch] : VOWELS_INDEP[ch];
      prevWasConsonant = false;
      i++;
      continue;
    }
    if (CONSONANTS[ch]) {
      if (prevWasConsonant) out += '್';
      out += CONSONANTS[ch];
      prevWasConsonant = true;
      i++;
      continue;
    }
    i++;
  }
  return out || word;
}

export function toKannadaName(name, existingKn) {
  if (existingKn && existingKn.trim()) return existingKn.trim();
  if (!name || !name.trim()) return '';
  const norm = name.trim().toLowerCase().replace(/\s+/g, ' ');
  if (KANNADA_DICTIONARY[norm]) return KANNADA_DICTIONARY[norm];
  // Check substring dictionary hit for exact road name without suffixes
  for (const [k, v] of Object.entries(KANNADA_DICTIONARY)) {
    if (norm === k) return v;
  }
  return name
    .trim()
    .split(/[\s\-/]+/)
    .map(transliterateWord)
    .filter(Boolean)
    .join(' ');
}
