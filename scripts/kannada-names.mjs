  b: 'ಬ', c: 'ಕ', d: 'ಡ', f: 'ಫ', g: 'ಗ', h: 'ಹ', j: 'ಜ', k: 'ಕ',
  l: 'ಲ', m: 'ಮ', n: 'ನ', p: 'ಪ', q: 'ಕ', r: 'ರ', s: 'ಸ', t: 'ಟ',
